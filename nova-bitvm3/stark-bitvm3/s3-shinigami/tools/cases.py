#!/usr/bin/env python3
"""Small script fixtures and exact Cairo public-input serialization.

Application labels describe intended consumers. These fixtures exercise CSV and
SHA256 gates only; they do not implement an Ark VTXO or UTXORef state machine.
"""
from __future__ import annotations
import hashlib
import json
import struct
from pathlib import Path

DOMAIN = int.from_bytes(b"SHINIGAMI_BITVM3_V1", "big")
FLAGS = 0x518
CAIRO_P = 2**251 + 17 * 2**192 + 1


def byte_array(data: bytes) -> list[int]:
    n, rest = divmod(len(data), 31)
    return [n, *[int.from_bytes(data[i*31:(i+1)*31], "big") for i in range(n)],
            int.from_bytes(data[n*31:], "big"), rest]


def transaction(script_sig: bytes = b"", *, sequence: int = 10, version: int = 2,
                locktime: int = 0) -> bytes:
    if len(script_sig) > 75:
        raise ValueError("fixture scriptSig exceeds one-byte CompactSize budget")
    return (struct.pack("<I", version) + b"\x01" + bytes.fromhex("11"*32)
            + struct.pack("<I", 0) + bytes([len(script_sig)]) + script_sig
            + struct.pack("<I", sequence) + b"\x01" + struct.pack("<Q", 900)
            + b"\x01\x51" + struct.pack("<I", locktime))


def request(case_id: int, app: int, tx: bytes, script: bytes) -> list[int]:
    return [3, app, case_id, 0, *byte_array(tx), 1000, *byte_array(script), 100]


def cases() -> list[dict]:
    csv = bytes.fromhex("5ab27551")
    preimage = b"utxoref-s3"
    lock = b"\xa8\x20" + hashlib.sha256(preimage).digest() + b"\x87"
    examples = [
        ("csv_valid", 1, transaction(), csv, True),
        ("csv_below_delay", 1, transaction(sequence=9), csv, False),
        ("csv_old_tx_version", 1, transaction(version=1), csv, False),
        ("csv_disabled_sequence", 1, transaction(sequence=1 << 31), csv, False),
        ("csv_wrong_time_unit", 1, transaction(sequence=(1 << 22) | 10), csv, False),
        ("hashlock_valid", 2, transaction(bytes([len(preimage)]) + preimage), lock, True),
        ("hashlock_wrong_preimage", 2,
         transaction(bytes([len(preimage)]) + b"utxoref-s4"), lock, False),
        ("hashlock_wrong_commitment", 2,
         transaction(bytes([len(preimage)]) + preimage),
         b"\xa8\x20" + hashlib.sha256(b"other-key").digest() + b"\x87", False),
    ]
    return [dict(name=name, application=app, raw_transaction=tx.hex(),
                 prevout_script=script.hex(), expected_accept=accept,
                 args=request(i+1, app, tx, script))
            for i, (name, app, tx, script, accept) in enumerate(examples)]


def write_cases(destination: Path) -> None:
    destination.mkdir(parents=True, exist_ok=True)
    fixtures = cases()
    for item in fixtures:
        (destination / (item["name"] + ".args.json")).write_text(
            json.dumps([hex(x) for x in item["args"]]) + "\n")
    (destination / "cases.json").write_text(json.dumps(fixtures, indent=2) + "\n")


def write_cairo_tests(destination: Path) -> None:
    """Generate assertions against the real imported engine, not a Python model."""
    def literal(h: str) -> str:
        return '"' + ''.join('\\x' + h[i:i+2] for i in range(0,len(h),2)) + '"'
    lines = ['// Generated by tools/cases.py; synthetic script-component cases.',
             'use super::{Request, main, FLAGS};',
             'fn check(request: Request, expected: bool) {',
             '    let original = request.clone();',
             '    let receipt = main(request);',
             "    assert(receipt.accepted == expected, 'unexpected script verdict');",
             "    assert(receipt.domain == 'SHINIGAMI_BITVM3_V1', 'domain changed');",
             "    assert(receipt.schema == 1 && receipt.scope == 1, 'scope changed');",
             "    assert(receipt.flags == FLAGS, 'flags changed');",
             "    assert(receipt.request.raw_transaction == original.raw_transaction, 'transaction changed');",
             "    assert(receipt.request.prevout_script == original.prevout_script, 'prevout changed');",
             "    assert(receipt.request.request_id == original.request_id, 'request changed');",
             '}', '']
    for i, item in enumerate(cases(),1):
        lines += ['#[test]', f'fn {item["name"]}() {{',
                  f'    check(Request {{ network: 3, application: {item["application"]}, request_id: {i},',
                  f'        raw_transaction: {literal(item["raw_transaction"])},',
                  f'        prevout_amount: 1000, prevout_script: {literal(item["prevout_script"])},',
                  f'        prevout_height: 100 }}, {str(item["expected_accept"]).lower()});', '}', '']
    destination.write_text('\n'.join(lines))


if __name__ == "__main__":
    import sys
    write_cases(Path(sys.argv[1]))
    write_cairo_tests(Path(__file__).resolve().parents[1]/"src/tests.cairo")
